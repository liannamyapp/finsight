import { useInsights } from '../api/hooks';

const ICONS = { info: 'ℹ', warning: '!', positive: '↑' } as const;

export function InsightsPanel() {
  const insights = useInsights();

  return (
    <section className="card">
      <div className="card-header">
        <div>
          <h2>AI insights</h2>
          <p className="muted">Generated from aggregated data for the selected period.</p>
        </div>
        <button className="btn btn-primary" onClick={() => insights.mutate()} disabled={insights.isPending}>
          {insights.isPending ? 'Analyzing…' : insights.data ? 'Regenerate' : 'Generate insights'}
        </button>
      </div>

      {insights.isError && <p className="error">{insights.error?.message}</p>}

      {insights.data && (
        <>
          <span className={`badge ${insights.data.source === 'llm' ? 'badge-ai' : ''}`}>
            {insights.data.source === 'llm' ? 'Generated by LLM' : 'Rule-based (no LLM key configured)'}
          </span>
          <ul className="insights">
            {insights.data.insights.map((item) => (
              <li key={item.title} className={`insight insight-${item.level}`}>
                <span className="insight-icon">{ICONS[item.level]}</span>
                <div>
                  <strong>{item.title}</strong>
                  <p>{item.text}</p>
                </div>
              </li>
            ))}
          </ul>
        </>
      )}
    </section>
  );
}
